import {contextBridge,ipcRenderer} from 'electron';import type {ThoughtlineBridge} from '../shared/bridge';
const api:ThoughtlineBridge={
 resizeComposer:(height,session)=>ipcRenderer.invoke('thoughtline:composer-size',height,session),
 reminderAction:(key,open)=>ipcRenderer.invoke('thoughtline:reminder-action',key,open),
 notificationAccess:request=>ipcRenderer.invoke('thoughtline:notification-access',request===true),
 openNotificationSettings:()=>ipcRenderer.invoke('thoughtline:notification-settings'),
 setReminder:(id,at,expected,session)=>ipcRenderer.invoke('thoughtline:set-reminder',id,at,expected,session),
 setPreferences:(patch,sequence)=>ipcRenderer.invoke('thoughtline:preferences',patch,sequence),
 storageInfo:()=>ipcRenderer.invoke('thoughtline:storage-info'),
 openStorageDirectory:()=>ipcRenderer.invoke('thoughtline:open-storage-directory'),
 changeStorage:()=>ipcRenderer.invoke('thoughtline:change-storage'),
 exportBackup:()=>ipcRenderer.invoke('thoughtline:export-backup'),
 selectClip:(id,ideaId,sequence)=>ipcRenderer.invoke('thoughtline:select-clip',id,ideaId,sequence),
 onPrepareLeave:callback=>{const listener=async(_e:Electron.IpcRendererEvent,id:string)=>{let ok=false;try{ok=await callback();}catch{}ipcRenderer.send('thoughtline:leave-ready',id,ok);};ipcRenderer.on('thoughtline:prepare-leave',listener);return()=>ipcRenderer.removeListener('thoughtline:prepare-leave',listener);},
 info:()=>ipcRenderer.invoke('thoughtline:info'),
 onInfo:callback=>{const listener=(_event:Electron.IpcRendererEvent,info:Parameters<typeof callback>[0])=>callback(info);ipcRenderer.on('thoughtline:info-update',listener);return()=>ipcRenderer.removeListener('thoughtline:info-update',listener);},
 hitRects:layout=>ipcRenderer.send('thoughtline:hit-layout',layout),
 presentationFinished:session=>ipcRenderer.send('thoughtline:presentation-finished',session),
 copy:id=>ipcRenderer.invoke('thoughtline:copy',id),
 submit:(draft,revision,intent,reveal)=>ipcRenderer.invoke('thoughtline:submit',draft,revision,intent,reveal),
 placeIdea:(id,intent,revision,reveal,session)=>ipcRenderer.invoke('thoughtline:place-idea',id,intent,revision,reveal,session),
 close:draft=>ipcRenderer.invoke('thoughtline:close',draft),
 saveDraft:(draft,session,sequence)=>ipcRenderer.invoke('thoughtline:save-draft',draft,session,sequence),
 openComposer:sourceId=>ipcRenderer.invoke('thoughtline:open-composer',sourceId),
 openClassification:(tab,returnDraft)=>ipcRenderer.invoke('thoughtline:open-classification',tab,returnDraft),
 returnClassification:()=>ipcRenderer.invoke('thoughtline:return-classification'),
 classificationChange:(change,revision)=>ipcRenderer.invoke('thoughtline:classification',change,revision),
 openManage:(id,titles)=>ipcRenderer.invoke('thoughtline:open-manage',id,titles),
 closeManage:()=>ipcRenderer.invoke('thoughtline:close-manage'),
 openEdit:id=>ipcRenderer.invoke('thoughtline:open-edit',id),
 updateIdea:(id,draft,expectedDraft,manageSession)=>ipcRenderer.invoke('thoughtline:update-idea',id,draft,expectedDraft,manageSession),
 setEditing:(active,manageSession,ideaId)=>ipcRenderer.invoke('thoughtline:set-editing',active,manageSession,ideaId),
 ideaHistory:(id,kind,revision)=>ipcRenderer.invoke('thoughtline:idea-history',id,kind,revision),
 shelfMenu:id=>ipcRenderer.invoke('thoughtline:shelf-menu',id),
 returnCalendar:()=>ipcRenderer.invoke('thoughtline:return-calendar'),
 openSettings:()=>ipcRenderer.invoke('thoughtline:open-settings'),
 saveSettings:(settings,revision)=>ipcRenderer.invoke('thoughtline:settings',settings,revision),
 onPrepareQuit:callback=>{const listener=(_e:Electron.IpcRendererEvent,id:string)=>{let draft=null;try{draft=callback();}catch{}ipcRenderer.send('thoughtline:quit-draft',id,draft);};ipcRenderer.on('thoughtline:prepare-quit',listener);return()=>ipcRenderer.removeListener('thoughtline:prepare-quit',listener);},
 onQuitError:callback=>{const listener=(_e:Electron.IpcRendererEvent,message:string)=>callback(message);ipcRenderer.on('thoughtline:quit-error',listener);return()=>ipcRenderer.removeListener('thoughtline:quit-error',listener);},
 setStatus:(id,status,revision)=>ipcRenderer.invoke('thoughtline:status',id,status,revision),
 dragLock:active=>ipcRenderer.invoke('thoughtline:drag-lock',active),
 textDrag:(active,id)=>ipcRenderer.send('thoughtline:text-drag',active,id),
 clipChange:(change,revision)=>ipcRenderer.invoke('thoughtline:clip',change,revision),
 projectDelete:(project,revision,replacement)=>ipcRenderer.invoke('thoughtline:project-delete',project,revision,replacement),
 agentChange:(change,revision)=>ipcRenderer.invoke('thoughtline:agent',change,revision)
};
contextBridge.exposeInMainWorld('thoughtline',api);
